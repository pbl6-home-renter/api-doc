const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'reference/rentify.json'), 'utf8'));
const operation = spec.paths['/auth/register'].post;
const examples = operation.requestBody.content['application/json'].examples;
const validBody = examples.registeredTenant.value;
const headers = [
  { key: 'Content-Type', value: 'application/json', type: 'text' },
  { key: 'Accept', value: 'application/json', type: 'text' },
];
const controlledCases = {
  invalidHeader: 'Mock only: cần cấu hình mock/server trả INVALID_HEADER. Contract chưa chỉ rõ header nào và quy tắc nào bị vi phạm; không giả định thiếu Authorization là lỗi vì endpoint public.',
  badRequest: 'Mock only: cần cấu hình mock/server cho lỗi BAD_REQUEST khác. Không dùng JSON sai cú pháp, thiếu trường hoặc dữ liệu trùng để giả lập mã này.',
  validationFailed: 'Mock only: cần cấu hình mock/server cho lỗi validation chưa có mã riêng. Các lỗi trường đã mô tả phải trả mã cụ thể thay vì VALIDATION_FAILED.',
  tooManyRequests: 'Cần vượt hạn mức của cùng client trong cửa sổ rate limit hoặc chọn mock 429. Một request hợp lệ riêng lẻ không bảo đảm trả 429.',
  internalServerError: 'Mock only: cấu hình mock hoặc fault injection có kiểm soát phía server trả 500. Body hợp lệ riêng lẻ không gây lỗi server.',
};
const requestNotes = {
  ...controlledCases,
  invalidJson: 'Raw body thiếu phần đóng JSON; giữ Content-Type application/json để kiểm thử lỗi parse JSON.',
};
const cases = [];

function resolveResponse(response) {
  if (!response.$ref) return response;
  return response.$ref.slice(2).split('/').reduce((node, key) => node[key], spec);
}

function addCase(key, status, responseBody, response, note) {
  const sample = examples[key];
  const body = sample?.value ?? validBody;
  const request = {
    method: 'POST',
    header: structuredClone(headers),
    auth: { type: 'noauth' },
    url: {
      raw: '{{baseUrl}}/auth/register',
      host: ['{{baseUrl}}'],
      path: ['auth', 'register'],
    },
    description: [
      `Kỳ vọng HTTP ${status}, code ${responseBody.code}.`,
      sample?.description || note || 'Các trường còn lại hợp lệ; chỉ thay đổi điều kiện đang kiểm thử.',
      'Không có query params, path params, Authorization hoặc cookie đầu vào.',
      'Mock URL có apidogResponseId chọn response cố định; nó không xác nhận body thực sự gây ra lỗi. Dùng API case trong Run với môi trường Local Mock hoặc backend để gửi body của case.',
    ].join('\n\n'),
    body: {
      mode: 'raw',
      raw: key === 'invalidJson' ? '{"email":"lan@example.com",' : JSON.stringify(body, null, 2),
      options: { raw: { language: 'json' } },
    },
  };
  if (key === 'missingBody') delete request.body;
  const responseHeaders = [{ key: 'Content-Type', value: 'application/json' }];
  for (const [name, header] of Object.entries(response.headers || {})) {
    const value = header.example ?? header.schema?.example;
    if (value !== undefined) responseHeaders.push({ key: name, value: String(value) });
  }
  cases.push({
    name: `${status} ${responseBody.code} — ${key}`,
    originalRequest: request,
    status: { 201: 'Created', 400: 'Bad Request', 409: 'Conflict', 422: 'Unprocessable Entity', 429: 'Too Many Requests', 500: 'Internal Server Error' }[status],
    code: Number(status),
    header: responseHeaders,
    body: JSON.stringify(responseBody, null, 2),
    _postman_previewlanguage: 'json',
    cookie: [],
  });
}

for (const [status, unresolved] of Object.entries(operation.responses)) {
  const response = resolveResponse(unresolved);
  const media = response.content['application/json'];
  if (status === '201') {
    for (const key of ['registeredTenant', 'registeredLandlord']) {
      const { password, ...data } = examples[key].value;
      addCase(key, status, { ...media.example, data: { ...media.example.data, ...data } }, response);
    }
  } else if (media.examples) {
    for (const [key, example] of Object.entries(media.examples)) {
      if (!examples[key] && key !== 'invalidJson' && !controlledCases[key]) {
        throw new Error(`Missing request scenario for ${key}`);
      }
      addCase(key, status, example.value, response, requestNotes[key]);
    }
  } else {
    const key = status === '429' ? 'tooManyRequests' : 'internalServerError';
    addCase(key, status, media.example, response, controlledCases[key]);
  }
}
addCase('missingBody', '400', { statusCode: 400, code: 'INVALID_REQUEST_BODY' }, resolveResponse(operation.responses['400']), 'Không gửi body; khác với object rỗng {} vốn gây lỗi thiếu trường 422.');

const collection = {
  info: {
    name: 'Rentify — Register request cases',
    description: 'Generated by npm run bundle. Import vào Apidog dưới dạng API Cases để giữ request riêng cho từng response. Xem reference/register-mock-guide.md.',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [{ key: 'baseUrl', value: spec.servers[0].url, type: 'string' }],
  item: [{ name: 'Auth', item: [{ name: 'Register', request: cases[0].originalRequest, response: cases }] }],
};
fs.writeFileSync(path.join(root, 'reference/register-cases.postman.json'), JSON.stringify(collection, null, 2) + '\n');
console.log(`Generated ${cases.length} Register request/response cases.`);
